// Writes only to a disposable server on port 8768, never the review workspace.
const {chromium}=require('../.superpowers/review-browser-check/node_modules/playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true});
 try {
  const page=await browser.newPage(); const base='http://127.0.0.1:8768';
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const before=await(await page.request.get(base+'/api/reviews')).json();
  await page.goto(base);
  await page.getByRole('button',{name:'Phân tích lỗi',exact:true}).click();
  await page.getByRole('checkbox',{name:'Cần đối chiếu comment cũ (13)',exact:true}).check();
  await page.locator('[data-analysis-sample="train_1178"]').click();
  const note=page.getByRole('textbox',{name:'Ghi chú đối chiếu',exact:true});
  const status=page.getByRole('combobox',{name:'Trạng thái đối chiếu',exact:true});
  await status.selectOption('agree'); await note.fill('I checked available=true; missing reserve.');
  await page.locator('[data-analysis-sample="train_1412"]').click();
  await page.locator('[data-analysis-sample="train_1178"]').click();
  assert.equal(await note.inputValue(),'I checked available=true; missing reserve.');
  await page.getByRole('button',{name:'Nhận xét',exact:true}).click();
  await page.getByRole('button',{name:'Phân tích lỗi',exact:true}).click();
  assert.equal(await note.inputValue(),'I checked available=true; missing reserve.');
  await page.getByRole('button',{name:'Lưu đối chiếu',exact:true}).click();
  await page.getByText('Đã lưu đối chiếu vào SQLite.',{exact:true}).waitFor();
  await page.reload();
  await page.getByRole('button',{name:'Phân tích lỗi',exact:true}).click();
  await page.getByRole('checkbox',{name:'Cần đối chiếu comment cũ (13)',exact:true}).check();
  const filter=page.getByRole('combobox',{name:'Lọc trạng thái đối chiếu',exact:true});
  await filter.selectOption('agree');
  assert.equal(await page.locator('[data-analysis-sample]').count(),1);
  assert.equal(await status.inputValue(),'agree');
  assert.equal(await note.inputValue(),'I checked available=true; missing reserve.');
  await filter.selectOption('unreviewed');
  assert.equal(await page.locator('[data-analysis-sample]').count(),12);
  await filter.selectOption('agree');
  await status.selectOption('needs_check');
  await page.getByRole('button',{name:'Lưu đối chiếu',exact:true}).click();
  await page.getByText('Không có sample phù hợp bộ lọc.',{exact:true}).waitFor();
  await filter.selectOption('needs_check');
  assert.equal(await page.locator('[data-analysis-sample]').count(),1);
  const data=await(await page.request.get(base+'/api/analysis')).json();
  const url=base+'/api/analysis-feedback/train_1178';
  assert.equal((await page.request.put(url,{data:{analysis_key:data.feedback_key,status:'disagree',revision:0}})).status(),409);
  assert.equal((await page.request.put(url,{data:{analysis_key:'stale',status:'agree',revision:2}})).status(),409);
  assert.equal((await page.request.put(base+'/api/analysis-feedback/unknown',{data:{}})).status(),404);
  const exported=await(await page.request.get(base+'/api/export')).json();
  assert.equal(exported.analysis_feedback[0].status,'needs_check');
  assert.deepEqual(await(await page.request.get(base+'/api/reviews')).json(),before);
  assert.deepEqual(errors,[]);
  console.log('PASS: persistence, draft navigation, 13/12 status filters, reopen, conflicts, export, unchanged reviews.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
